import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const { PGlite } = await import(pathToFileURL(process.env.PGLITE_MODULE).href);
const db = new PGlite();
await db.exec(`
CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY);
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT null::uuid $$;
CREATE FUNCTION public.is_staff_or_admin() RETURNS boolean LANGUAGE sql AS $$ SELECT false $$;
CREATE TABLE public.user_profiles(id uuid PRIMARY KEY, short_code text);
CREATE TABLE public.orders(id uuid PRIMARY KEY, customer_id uuid, order_number text, order_type text DEFAULT 'regular', status text, payment_status text, purchase_type text DEFAULT 'online', updated_at timestamptz DEFAULT now());
CREATE TABLE public.order_notification_events(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),order_id uuid,notification_type text,status text DEFAULT 'pending',attempt_count integer DEFAULT 0,language text DEFAULT 'en',claimed_at timestamptz,first_attempt_at timestamptz,updated_at timestamptz,last_error text);
CREATE TABLE public.cms_settings(setting_key text PRIMARY KEY,value text);
CREATE TABLE public.cms_labels(key text PRIMARY KEY,text_en text,text_th text,text_zh text);
`);
await db.exec(await readFile('supabase/migrations/20261012145114_customer_receipt_pickup_completion_v1.sql','utf8'));
const file=(await readdir('supabase/migrations')).find(f=>f.endsWith('_joko_specials_receipt_compatibility_v1.sql'));
await db.exec(await readFile(`supabase/migrations/${file}`,'utf8'));
let checks=0;
const eq=(a,b)=>{assert.deepEqual(a,b);checks++;};
const row=async(sql,args=[]) => (await db.query(sql,args)).rows[0];
const regular='10000000-0000-0000-0000-000000000001';
const special='10000000-0000-0000-0000-000000000002';
await db.query("INSERT INTO orders(id,order_number,order_type,status,payment_status) VALUES ($1,'REGULAR','regular','picked_up','paid'),($2,'SPECIAL','specials','picked_up','paid')",[regular,special]);
for (const id of [regular,special]) await db.query("INSERT INTO order_notification_events(order_id,notification_type) VALUES ($1,'customer_confirmation')",[id]);
eq((await row("SELECT claim_order_notification($1,'customer_confirmation') r",[special])).r.outcome,'unavailable');
eq((await row("SELECT status FROM order_notification_events WHERE order_id=$1",[special])).status,'pending');
eq((await row("SELECT claim_order_notification($1,'customer_confirmation') r",[regular])).r.outcome,'claimed');
await db.query("INSERT INTO pickup_handoff_sessions(order_id,token_hash,expires_at) VALUES ($1,$2,now()+interval '1 hour'),($3,$4,now()+interval '1 hour')",[regular,'r'.repeat(64),special,'s'.repeat(64)]);
await assert.rejects(()=>db.query("SELECT complete_order_customer_receipt($1,'RECEIPT-SPECIAL',now(),'{}')",['s'.repeat(64)]),/Specials receipt confirmation workflow/);checks++;
eq((await row('SELECT status FROM orders WHERE id=$1',[special])).status,'picked_up');
eq((await row('SELECT count(*)::integer n FROM order_receipts WHERE order_id=$1',[special])).n,0);
const first=(await row("SELECT complete_order_customer_receipt($1,'RECEIPT-REGULAR',now(),'{}') r",['r'.repeat(64)])).r;
eq(first.receipt_number,'RECEIPT-REGULAR');
eq((await row('SELECT status FROM orders WHERE id=$1',[regular])).status,'completed');
const replay=(await row("SELECT complete_order_customer_receipt($1,'DUPLICATE',now(),'{\"changed\":true}') r",['r'.repeat(64)])).r;
eq(replay.receipt_number,'RECEIPT-REGULAR');eq(replay.already_confirmed,true);
eq((await row('SELECT count(*)::integer n FROM order_receipts WHERE order_id=$1',[regular])).n,1);
for(const role of ['anon','authenticated']) eq((await row("SELECT has_function_privilege($1,'public.complete_order_customer_receipt(text,text,timestamptz,jsonb)','EXECUTE') ok",[role])).ok,false);
eq((await row("SELECT has_function_privilege('service_role','public.complete_order_customer_receipt(text,text,timestamptz,jsonb)','EXECUTE') ok")).ok,true);
console.log(`${checks} receipt compatibility assertions passed (actual production receipt migration, isolated Postgres).`);
await db.close();
